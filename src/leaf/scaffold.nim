    ("app/pages/home/views/search.nim", staticRead("templates/scaffold/home_search.nim")),
    ("app/pages/home/views/settings.nim", staticRead("templates/scaffold/home_settings.nim")),
    ("config/routes.nim", staticRead("templates/scaffold/routes.nim")),
    ("README.md", staticRead("templates/scaffold/README.md"))]

proc pageRegistry(resources: seq[ResourceSpec], modelSchema: int): string =
  result = GeneratedHeader & "import leaf\n"
  if modelSchema == 1: result.add("import leaf/sqlite as storage\n")
  result.add("import ../pages/home/page as home_page\n")
  for resource in resources:
    result.add("import ../pages/" & resource.plural & "/page as " & resource.plural & "_page\n")
  if modelSchema == 1:
    result.add("\nproc generatedPages*(database: storage.Database): seq[PageDefinition] =\n  @[home_page.definition(database)")
    for resource in resources: result.add(",\n    " & resource.plural & "_page.definition(database)")
  else:
    result.add("\nproc generatedPages*(): seq[PageDefinition] =\n  @[home_page.definition()")
    for resource in resources: result.add(",\n    " & resource.plural & "_page.definition()")
  result.add("]\n")

proc routeRegistry(resources: seq[ResourceSpec]): string =
  result = GeneratedHeader & "import leaf\n\nproc generatedRoutes*(): seq[Route] =\n  @[\n    Route(name: \"home\", path: \"/\", page: \"home\", view: \"index\"),\n    Route(name: \"search\", path: \"/search\", page: \"home\", view: \"search\"),\n    Route(name: \"settings\", path: \"/settings\", page: \"home\", view: \"settings\")"
  for resource in resources:
    let p = resource.plural
    result.add(",\n    Route(name: \"" & p & "\", path: \"/" & p & "\", page: \"" & p & "\", view: \"index\")")
  result.add("\n  ]\n")

proc manifest(resources: seq[ResourceSpec], modelSchema: int): string =
  ## Schema 3 keeps business model semantics separate from the manifest revision;
  ## migration versions are decimal strings so int64 survives every JSON reader.
  var entries = newJArray()
  for resource in resources:
    var fields = newJArray()
    for field in resource.fields: fields.add(%*{"name": field.name, "type": field.kind})
    entries.add(%*{"model": resource.model, "singular": resource.singular,
      "fields": fields, "migration": $resource.migration})
  var value = %*{"schema": ScaffoldSchema, "model_schema": modelSchema, "resources": entries}
  if modelSchema == 2:
    value["model_api"] = %1
    value["timestamps"] = %true
  pretty(value) & "\n"

proc ensureNoMigrationCollision(root: string, resource: ResourceSpec) =
  ## The proposed logical migration name must not already exist in the catalog.
  for file in migrations.scanMigrationFiles(root / MigrationsDir):
    if file.name == "create_" & resource.plural:
      fail("migration already exists: create_" & resource.plural)

proc loadManifest(root: string): ScaffoldManifest =
  let path = guardedPath(root, ManifestPath)
  if not fileExists(path):
    fail("resource generation needs a scaffold application; create one in the current directory")
  result = readCanonicalManifest(parseFile(path))
  checkManifestSources(root, result.resources, result.schema != 3,
    (if result.schema != 3: 1 else: 0))
  for file in [ScaffoldFile(path: PagesPath, content: pageRegistry(result.resources, result.modelSchema)),
      ScaffoldFile(path: RoutesPath, content: routeRegistry(result.resources))]:
    let registered = guardedPath(root, file.path)
    if not fileExists(registered) or readFile(registered) != file.content:
      fail("generated registry was modified or is missing: " & file.path)

proc appFiles(name: string, taskVersion: int64): seq[ScaffoldFile] =
  const
    modelApplication = staticRead("templates/scaffold/model_application.nim")
    modelPage = staticRead("templates/scaffold/model_home_page.nim")
    modelLogic = staticRead("templates/scaffold/model_home_logic.nim")
    modelReadme = staticRead("templates/scaffold/model_README.md")
  for (path, content) in Templates:
    var selected = content
    case path
    of "app/application.nim": selected = modelApplication
    of "app/pages/home/page.nim": selected = modelPage
    of "app/pages/home/logic.nim": selected = modelLogic
    of "README.md": selected = modelReadme
    else: discard
    result.add(ScaffoldFile(path: path, content: selected.replace("{{name}}", name)))
  result.add(ScaffoldFile(path: "config.nims", content: "import std/strutils\nimport leaf/orm_config\nfor argument in ormCompilerArgs(OrmSourceRoot):\n  let pair = argument.split(\":\", 1)\n  switch(pair[0].strip(chars = {'-'}), pair[1])\n"))
  result.add(ScaffoldFile(path: "app/models/application_record.nim", content: "import leaf/model\n\ntype ApplicationRecord* = ref object of TimestampedRecord\ndefineAbstractModel(ApplicationRecord)\n"))
  result.add(ScaffoldFile(path: "leaf.json", content: pretty(newProjectConfig(name, "main.nim",
    @["main.nim", "app", "config", "db", "assets"])) & "\n"))
  result.add(ScaffoldFile(path: ".gitignore", content: "/target/\n/dist/\n*.core\n"))
  result.add(ScaffoldFile(path: "assets/message.txt", content: "Leaf page-group application\n"))
  result.add(ScaffoldFile(path: "config/application.nim", content:
    "const\n  ApplicationTitle* = " & name.escape & "\n  WindowWidth* = 960\n  WindowHeight* = 640\n"))
  result.add(ScaffoldFile(path: DatabaseConfigPath, content: databaseConfigSource(name)))
  result.add(ScaffoldFile(path: CatalogPath, content: catalogSource()))
  result.add(ScaffoldFile(path: MigrationsDir / "README.md", content: migrationsReadmeSource()))
  let task = parseResource("Task", @["title:string", "done:bool"], taskVersion)
  result.add(ScaffoldFile(path: "app/models/task.nim", content: modelCodeV2(task)))
  result.add(ScaffoldFile(path: "tests/test_home.nim", content: modelTestCodeV2(task)))
  result.add(migrationFile(task, 2))
  result.add(ScaffoldFile(path: PagesPath, content: pageRegistry(@[], 2)))
  result.add(ScaffoldFile(path: RoutesPath, content: routeRegistry(@[])))
  result.add(ScaffoldFile(path: ManifestPath, content: manifest(@[], 2)))

proc resourceFilesFor(resource: ResourceSpec, modelSchema: int): seq[ScaffoldFile] =
  if modelSchema == 1:
    result = resourceFiles(resource)
    result.add(migrationFile(resource, 1))
    result.add(ScaffoldFile(path: "tests/test_" & resource.plural & ".nim", content: testCode(resource)))
  else:
    result = resourceFilesV2(resource)
    result.add(migrationFile(resource, 2))
    result.add(ScaffoldFile(path: "tests/test_" & resource.plural & ".nim", content: modelTestCodeV2(resource)))

proc resourcePlan(root, name: string, loaded: ScaffoldManifest,
    resource: ResourceSpec): seq[ScaffoldFile] =
  result = resourceFilesFor(resource, loaded.modelSchema)
  var resources = loaded.resources
  resources.add(resource)
  for file in [ScaffoldFile(path: PagesPath, content: pageRegistry(resources, loaded.modelSchema)),
      ScaffoldFile(path: RoutesPath, content: routeRegistry(resources)),
      ScaffoldFile(path: ManifestPath, content: manifest(resources, loaded.modelSchema))]:
    var updated = file
    updated.update = true
    updated.previous = readFile(guardedPath(root, file.path))
    result.add(updated)
  for file in databaseInitPlan(root, name, false): result.add(file)

proc nextVersion(root: string): int64 =
  migrations.nextMigrationVersion(
    migrations.scanMigrationFiles(root / MigrationsDir), getTime())

proc actions(plan: seq[ScaffoldFile]): seq[string] =
  for file in plan: result.add((if file.update: "update " else: "create ") & file.path)

proc generateScaffold*(options: ScaffoldOptions, root: string): seq[string] =
  ## Mandatory explicit root. Application mode writes into the existing current
  ## directory; resource mode uses the nearest project root chosen by the caller.
  let normalized = normalizedPath(absolutePath(root))
  if options.mode == smApplication:
    let name = normalized.extractFilename
    if name.len == 0 or name in [".", "/"]:
      fail("cannot derive an application name from " & root)
    proc applicationPlan(): seq[ScaffoldFile] =
      # Allocate from the ACTUAL existing migrations, never an empty catalog.
      let existingFiles = migrations.scanMigrationFiles(normalized / MigrationsDir)
      for file in existingFiles:
        if file.name == "create_tasks":
          fail("migration already exists: create_tasks")
      result = appFiles(name, migrations.nextMigrationVersion(existingFiles, getTime()))
      # Guard every retained minimal artifact before reading it for the matcher.
      for retained in ["leaf.json", "assets/message.txt", "src/main.nim", "src/app.nim"]:
        discard guardedPath(normalized, retained)
      if matchesMinimalTemplate(normalized):
        # Untouched `leaf init` upgrade: only leaf.json and the example asset are
        # replaced; src/main.nim and src/app.nim stay exactly as generated.
        for index in 0 ..< result.len:
          if result[index].path in ["leaf.json", "assets/message.txt"]:
            result[index].update = true
            result[index].previous = readFile(normalized / result[index].path)
    var plan = applicationPlan()
    # Ordinary static conflicts are rejected before the coordination lock.
    checkPlan(normalized, plan, false)
    if options.dryRun:
      return actions(plan)
    let lockPath = guardedPath(normalized, GenerationLockRelative)
    createDir(lockPath.parentDir)
    let lock = acquireFileLock(lockPath)
    try:
      # The lock spans the catalog re-read, allocation and the whole write plan.
      plan = applicationPlan()
      checkPlan(normalized, plan, false)
      result = actions(plan)
      writePlan(normalized, plan, false)
    finally:
      lock.release()
    return
  # Reject a visible symlinked caller root before readProject canonicalizes it.
  discard guardedPath(normalized, ManifestPath)
  let project = readProject(normalized)
  var loaded = loadManifest(project.root)
  var resource = parseResource(options.target, options.fields, nextVersion(project.root))
  checkResource(loaded.resources, resource)
  ensureNoMigrationCollision(project.root, resource)
  var plan = resourcePlan(project.root, project.name, loaded, resource)
  # Ordinary static conflicts are rejected before the coordination lock.
  checkPlan(project.root, plan, false)
  if options.dryRun:
    return actions(plan)
  let lockPath = guardedPath(project.root, GenerationLockRelative)
  createDir(lockPath.parentDir)
  let lock = acquireFileLock(lockPath)
  try:
    # The lock spans the manifest re-read, version allocation and the whole plan.
    loaded = loadManifest(project.root)
    resource = parseResource(options.target, options.fields, nextVersion(project.root))
    checkResource(loaded.resources, resource)
    ensureNoMigrationCollision(project.root, resource)
    plan = resourcePlan(project.root, project.name, loaded, resource)
    checkPlan(project.root, plan, false)
    result = actions(plan)
    writePlan(project.root, plan, false)
  finally:
    lock.release()
