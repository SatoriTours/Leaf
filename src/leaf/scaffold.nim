  PagesPath = "app/generated/pages.nim"
  RoutesPath = "config/generated/routes.nim"
  GeneratedHeader = "# Generated by leaf scaffold. Do not edit this file.\n"
  Templates = [
    ("main.nim", staticRead("templates/scaffold/main.nim")),
    ("app/application.nim", staticRead("templates/scaffold/application.nim")),
    ("app/shell.nim", staticRead("templates/scaffold/shell.nim")),
    ("app/components/empty_state.nim", staticRead("templates/scaffold/empty_state.nim")),
    ("app/pages/home/page.nim", staticRead("templates/scaffold/home_page.nim")),
