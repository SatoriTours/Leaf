## Database initialization for an existing Leaf project. Configuration and
## catalog files are planned and preflighted; importing them never opens storage.
import std/[json, os, strutils]
import ../[core, project, scaffold_files, scaffold_templates, scaffold_types]
import ./files as migrationFiles
import ./generator as migrationGenerator
import ./locking

const
  DatabaseConfigPath* = "config/database.nim"
  CatalogPath* = "db/catalog.nim"
  MigrationsDir* = "db/migrations"
  GeneratedHeader = "# Generated by leaf scaffold. Do not edit this file.\n"

proc catalogSource*(): string =
  GeneratedHeader & "import leaf/migrations\n\n" &
    "discoverMigrations(\"migrations\", applicationMigrations)\n"

proc databaseConfigSource*(name: string): string =
  ## Importing this configuration does not open storage; startup does.
  "## Importing configuration does not open storage; application startup does.\n" &
    "import std/os\nimport leaf/sqlite\nimport leaf/migrations\nimport ../db/catalog\n" &
    "export sqlite\n\n" &
    "proc databasePath*(): string =\n" &
    "  getEnv(\"LEAF_DATABASE_PATH\", getDataDir() / " & name.escape &
    " / \"application.sqlite3\")\n\n" &
    "proc openApplicationDatabase*(path = databasePath()): Database =\n" &
    "  result = openDatabase(path)\n" &
    "  try:\n    result.migrate(applicationMigrations())\n" &
    "  except CatchableError:\n    result.close()\n    raise\n"

proc migrationsReadmeSource*(): string =
  "# Migrations\n\nEach `.nim` file declares one restricted `migration` and is\n" &
    "discovered by `db/catalog.nim`. Legacy `.up.sql`/`.down.sql` pairs remain\n" &
    "readable and are never rewritten.\n\n" &
    "## Startup\n\nMigrations never run automatically when the configuration is imported.\n" &
    "Open storage explicitly from the application entry point:\n\n" &
    "```nim\nimport ./config/database\n\n" &
    "let db = openApplicationDatabase()\n```\n\n" &
    "`openApplicationDatabase` opens the configured path and applies pending\n" &
    "migrations. Importing `config/database` alone opens no storage and creates\n" &
    "no database file.\n"

proc legacyDatabaseConfigSource*(name: string): string =
  ## The exact old generated startup that delegated to a per-file registry.
  "## Importing configuration does not open storage; application startup does.\n" &
    "import std/os\nimport leaf/sqlite\nimport ../app/generated/migrations\nexport sqlite\n\n" &
    "proc databasePath*(): string =\n" &
    "  getEnv(\"LEAF_DATABASE_PATH\", getDataDir() / " & name.escape &
    " / \"application.sqlite3\")\n\n" &
    "proc openApplicationDatabase*(path = databasePath()): Database =\n" &
    "  result = openDatabase(path)\n" &
    "  try:\n    result.migrate(generatedMigrations())\n" &
    "  except CatchableError:\n    result.close()\n    raise\n"

proc recognizedDatabaseConfig*(previous, name: string): bool =
  ## Ownership requires byte-exact equality with the canonical old renderer; a
  ## marker or comment is not proof of generated ownership.
  previous == legacyDatabaseConfigSource(name)

proc databaseIncludeUpdate*(root: string): tuple[content, previous: string, needed: bool] =
  ## Validated JSON update: keep every existing field and append the database
  ## include entries only when they are missing.
  let path = root / "leaf.json"
  let previous = readFile(path)
  let value = parseJson(previous)
  if value.kind != JObject or "include" notin value or value["include"].kind != JArray:
    fail("leaf.json must declare an include array")
  var includes = value["include"]
  var changed = false
  for needed in ["config", "db"]:
    var present = false
    for item in includes:
      if item.kind == JString and item.getStr == needed: present = true
    if not present:
      includes.add(%needed)
      changed = true
  if not changed: return (content: previous, previous: previous, needed: false)
  var updated = value
  updated["include"] = includes
  (content: pretty(updated) & "\n", previous: previous, needed: true)

proc addDatabaseFile(plan: var seq[ScaffoldFile], root, path, content: string,
    recognized: proc(previous: string): bool, what: string) =
  let target = guardedPath(root, path)
  if not fileExists(target):
    plan.add(ScaffoldFile(path: path, content: content))
  else:
    let previous = readFile(target)
    if previous == content: return
    if recognized(previous):
      plan.add(ScaffoldFile(path: path, content: content, update: true, previous: previous))
    else:
      fail(what & " was customized; keep it and add the manual startup call: " & path)

const RegistryPath = "app/generated/migrations.nim"
const LegacyManifestPath = ".leaf/scaffold.json"

proc migrationDelegateSource*(): string =
  ## Stable compatibility delegate: it keeps the original `generatedMigrations`
  ## name and the original `db.migrate(generatedMigrations())` expression
  ## working, while returning the new typed descriptors through the catalog.
  GeneratedHeader & "import leaf/migrations\n" &
    "import ../../db/catalog as catalog\n" &
    "export migrations\n" &
    "export catalog\n\n" &
    "proc generatedMigrations*(): seq[MigrationDefinition] =\n" &
    "  catalog.applicationMigrations()\n"

proc legacyManifest(root: string): tuple[known, legacy: bool, manifest: ScaffoldManifest] =
  ## Classify scaffold provenance with the SAME strict canonical parser the
  ## scaffold itself uses; a manifest it would reject is never converted.
  let path = guardedPath(root, LegacyManifestPath)
  if not fileExists(path): return (false, false, ScaffoldManifest())
  result.known = true
  result.manifest = readCanonicalManifest(parseFile(path))
  result.legacy = result.manifest.schema in [1, 2]

proc checkManifestSources*(root: string, resources: seq[ResourceSpec], legacy = false,
    taskVersion: int64 = 0) =
  ## Every expected reference (the implicit Task migration plus every registered
  ## resource) must resolve to a real, correctly named migration of the expected
  ## version. Legacy references must additionally resolve to non-redirected
  ## `.up.sql` and `.down.sql` sources. Unrelated manual migrations stay allowed.
  let files = migrationFiles.scanMigrationFiles(root / MigrationsDir)
  var expected: seq[tuple[name: string, version: int64]]
  expected.add (name: "create_tasks", version: taskVersion)
  for resource in resources: expected.add (name: "create_" & resource.plural, version: resource.migration)
  for entry in expected:
    var found = false
    for file in files:
      if file.name == entry.name and (entry.version == 0 or file.version == entry.version):
        found = true
    if not found:
      fail("scaffold migration is missing or mismatched: " & entry.name &
        (if entry.version > 0: " at version " & $entry.version else: ""))
    if legacy:
      let padded = align($entry.version, 3, '0') & "_" & entry.name
      for direction in ["up", "down"]:
        let source = guardedPath(root, MigrationsDir & "/" & padded & "." & direction & ".sql")
        if not fileExists(source) or symlinkExists(source):
          fail("legacy migration source is missing or redirected: " & padded & "." &
            direction & ".sql")

proc registryPlan(root: string, convertManifest: bool): seq[ScaffoldFile] =
  ## Classify `app/generated/migrations.nim`: an exact old registry is converted
  ## in the same atomic plan, the stable delegate is idempotent, and anything
  ## else is custom and must be refused before any write.
  let classification = legacyManifest(root)
  let path = guardedPath(root, RegistryPath)
  var recognized = false
  if fileExists(path):
    let previous = readFile(path)
    if previous == migrationDelegateSource():
      recognized = true
    elif classification.legacy and previous == legacyMigrationRegistry(classification.manifest.resources):
      recognized = true
      result.add(ScaffoldFile(path: RegistryPath, content: migrationDelegateSource(),
        update: true, previous: previous))
    else:
      fail("app/generated/migrations.nim was customized; keep it or restore the generated file: " &
        RegistryPath)
  elif classification.legacy:
    fail("legacy scaffold registry is missing; restore " & RegistryPath &
      " before automatic conversion")
  if classification.known:
    # Validate the actual referenced sources before any write, including the
    # implicit Task migration, for every known scaffold (legacy, converted or
    # freshly generated), not only when a registry conversion is pending.
    checkManifestSources(root, classification.manifest.resources, classification.legacy,
      (if classification.legacy: 1 else: 0))
  if recognized and classification.legacy and convertManifest:
    # `databaseInitPlan` owns the manifest upgrade for plain initialization;
    # resource generation merges its own updated manifest instead.
    let manifestPath = guardedPath(root, LegacyManifestPath)
    result.add(ScaffoldFile(path: LegacyManifestPath,
      content: upgradedManifestSource(parseFile(manifestPath)),
      update: true, previous: readFile(manifestPath)))

proc databaseInitPlan*(root, name: string, convertManifest = true): seq[ScaffoldFile] =
  ## Config/catalog/readme/include additions; empty when everything matches.
  discard guardedPath(root, "leaf.json")
  addDatabaseFile(result, root, DatabaseConfigPath, databaseConfigSource(name),
    proc(previous: string): bool = recognizedDatabaseConfig(previous, name),
    "config/database.nim")
  # Only the exact current catalog is owned; any other content is custom.
  addDatabaseFile(result, root, CatalogPath, catalogSource(),
    proc(previous: string): bool = false, "db/catalog.nim")
  let readmePath = guardedPath(root, MigrationsDir / "README.md")
  if not fileExists(readmePath):
    result.add(ScaffoldFile(path: MigrationsDir / "README.md", content: migrationsReadmeSource()))
  for file in registryPlan(root, convertManifest): result.add(file)
  let includeUpdate = databaseIncludeUpdate(root)
  if includeUpdate.needed:
    result.add(ScaffoldFile(path: "leaf.json", content: includeUpdate.content,
      update: true, previous: includeUpdate.previous))

proc initializeDatabaseProject*(project: Project, dryRun = false): seq[string] =
  ## Install config/database.nim, db/catalog.nim and the migrations directory in
  ## an existing project. Never opens or migrates a database.
  var plan = databaseInitPlan(project.root, project.name)
  if plan.len == 0: return @["initialized " & project.root]
  # Ordinary static conflicts are rejected before the coordination lock.
  checkPlan(project.root, plan, false)
  if dryRun:
    for file in plan: result.add((if file.update: "update " else: "create ") & file.path)
    return
  let lockPath = guardedPath(project.root, migrationGenerator.GenerationLockRelative)
  createDir(lockPath.parentDir)
  let lock = acquireFileLock(lockPath)
  try:
    # The lock spans the manifest re-read, planning and the whole write plan so
    # concurrent resource generation cannot lose an update.
    plan = databaseInitPlan(project.root, project.name)
    if plan.len == 0: return @["initialized " & project.root]
    checkPlan(project.root, plan, false)
    for file in plan:
      result.add((if file.update: "update " else: "create ") & file.path)
    writePlan(project.root, plan, false)
  finally:
    lock.release()
