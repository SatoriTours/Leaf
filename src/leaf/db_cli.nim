## Headless database maintenance. The CLI compiles a UI-free maintenance program
## that imports only the project configuration and catalog, then supervises it
## with a unique cancellation token and stable JSON reporting.
import std/[json, monotimes, options, os, sequtils, sets, strtabs, strutils, times]
import ./[build, cli_options, core, process_io, project, sqlite]
import ./migrations
import ./migrations/types
import ./migrations/initialization

const
  MaintenanceRelative* = "target/leaf-db"
  MaintenanceEntry* = "target/leaf-db/maintenance.nim"
  MaintenanceBinary* = "target/leaf-db/maintenance"
  CancelTokenEnv* = "LEAF_MIGRATION_CANCEL_TOKEN"
  ReportEnv* = "LEAF_MIGRATION_REPORT"
  TextReportEnv* = "LEAF_MIGRATION_TEXT_REPORT"
  GracefulCancelSeconds* = 10

proc maintenanceSource*(): string =
  ## The generated program imports configuration and catalog only: never
  ## `main.nim`, the UI, or the application's automatic open function.
  "## Generated by leaf db. Imports configuration and catalog only.\n" &
    "import std/os\n" &
    "import ../../config/database\n" &
    "import ../../db/catalog\n" &
    "import leaf/db_cli\n\n" &
    "exitMaintenance(runMaintenance(databasePath(), applicationMigrations(), commandLineParams()))\n"

proc exitMaintenance*(code: int) {.noreturn.} =
  ## Preserve the raw POSIX status (130) instead of Nim's int8 saturation.
  when defined(posix): quit(if code in 128..255: code - 256 else: code)
  else: quit(code)

proc commandName(kind: MigrationRequestKind): string =
  case kind
  of mrMigrate: "migrate"
  of mrRollback: "rollback"
  of mrForward: "forward"
  of mrUp: "up"
  of mrDown: "down"
  of mrStatus: "status"

proc childArgs(request: MigrationRequest, dryRun, jsonOutput: bool): seq[string] =
  result.add commandName(request.kind)
  if request.kind in [mrUp, mrDown] and request.target.isSome:
    result.add $request.target.get()
  elif request.kind == mrMigrate and request.target.isSome:
    result.add(@["--to", $request.target.get()])
  if request.kind in [mrRollback, mrForward] and request.steps != 1:
    result.add(@["--steps", $request.steps])
  if dryRun: result.add "--dry-run"
  if jsonOutput: result.add "--json"

proc cancellationRequested(): bool =
  let token = getEnv(CancelTokenEnv)
  token.len > 0 and fileExists(token)

proc emit(result: MigrationResult, jsonOutput: bool) =
  ## The authoritative internal transport is always the canonical JSON envelope;
  ## the presentation (JSON or the existing text rendering) is chosen by the
  ## parent from the validated document, so text commands keep working.
  let report = getEnv(ReportEnv)
  if report.len > 0:
    let temporary = report & ".tmp"
    writeFile(temporary, resultJson(result).pretty() & "\n")
    if fileExists(report): removeFile(report)
    moveFile(temporary, report)
  else:
    if jsonOutput: stdout.writeLine(resultJson(result).pretty())
    else: stdout.writeLine(resultText(result))

proc errorJson*(command, code, message: string): string =
  ## One stable object for parser/project/compiler failures under `--json`.
  var result = MigrationResult(command: command, executionConfirmed: true)
  result.errors.add MigrationIssue(code: code, message: message)
  resultJson(result).pretty()

proc databaseCommandName*(args: seq[string]): string =
  if args.len > 1 and args[0] == "db": args[1] else: "db"

proc wantsDatabaseJson*(args: seq[string]): bool =
  args.len >= 2 and args[0] == "db" and "--json" in args

proc failure(command, database, code, message: string, jsonOutput: bool,
    dryRun = false): int =
  var result = MigrationResult(command: command, database: database)
  result.dryRun = dryRun
  result.errors.add MigrationIssue(code: code, message: message)
  emit(result, jsonOutput)
  1

proc selectedCapabilityIssues*(catalog: openArray[MigrationDefinition],
    plan: MigrationPlan, version: tuple[major, minor, patch: int]): seq[MigrationIssue] =
  ## The exact selected-direction capability gate the controller runs, exposed so
  ## a regression can prove the negative path without an older SQLite runtime.
  for step in plan.steps:
    let index = findDefinition(catalog, step.version)
    if index < 0: continue
    let definition = catalog[index]
    if definition.format == mfSqlV1: continue
    let operations = if step.direction == mdUp: definition.upOps else: definition.downOps
    try:
      checkCapabilities(operations, version)
    except MigrationError as error:
      result.add MigrationIssue(code: error.issueCode, message: error.msg,
        version: some(step.version), file: definition.sourcePath,
        direction: some(step.direction))


proc runMaintenance*(databasePath: string, catalog: seq[MigrationDefinition],
    args: seq[string]): int =
  ## Execute one database command against `catalog` and print its report.
  var command: CliCommand
  try:
    command = parseCli(@["db"] & args)
  except CatchableError as error:
    return failure("db", databasePath, "invalid_arguments", error.msg, false)
  if command.kind != ccDatabase or command.databaseInit:
    return failure("db", databasePath, "invalid_arguments",
      "unsupported database command", command.jsonOutput)
  let name = commandName(command.request.kind)
  let jsonOutput = command.jsonOutput
  let request = command.request
  # `dry_run` in the report reflects the explicit caller option; `preview`
  # additionally covers status, which never executes.
  let preview = command.dryRun or request.kind == mrStatus
  let existing = fileExists(databasePath)
  var db: Database
  try:
    # Read-only preflight: an absent database is treated as empty history and
    # must not create a file, parent directory, history table or lock.
    db = if existing: openDatabaseReadOnly(databasePath) else: openDatabase(":memory:")
  except CatchableError as error:
    return failure(name, databasePath, "database_unusable", error.msg, jsonOutput,
      command.dryRun)
  var history: seq[MigrationRecord]
  var result = MigrationResult(command: name, database: databasePath)
  result.dryRun = command.dryRun
  try:
    history = readMigrationHistory(db)
  except CatchableError as error:
    result.executionConfirmed = true
    result.errors.add MigrationIssue(code: "history_unreadable", message: error.msg)
    db.close()
    emit(result, jsonOutput)
    return 1
  var applied = initHashSet[int64]()
  for record in history: applied.incl record.version
  # Known history: an empty database is version 0, not an unknown state.
  result.currentVersion = (if history.len > 0: some(history[^1].version) else: some(0'i64))
  result.pendingVersions = catalog.filterIt(it.version notin applied).mapIt(it.version)
  result.statuses = inspectMigrationHistory(catalog, history)
  var issues = catalogIssues(catalog)
  for record in history: issues.add recordIssues(catalog, record)
  # The accepted runner treats these as disclosures, not fatal history damage.
  var fatal: seq[MigrationIssue]
  for issue in issues:
    if issue.code notin ["pending_template", "legacy_unverified_down"]: fatal.add issue
  if fatal.len > 0:
    result.executionConfirmed = true
    for issue in fatal: result.errors.add issue
    db.close()
    emit(result, jsonOutput)
    return 1
  var plan: MigrationPlan
  try:
    plan = planMigrations(catalog, history, request)
  except MigrationError as error:
    result.executionConfirmed = true
    result.errors.add MigrationIssue(code: error.issueCode, message: error.msg,
      version: error.migrationVersion, file: error.file, direction: error.direction)
    db.close()
    emit(result, jsonOutput)
    return 1
  # Capability preflight on the read-only handle: an unsupported selected
  # direction must fail before any writable open creates a database or parent.
  let capabilityIssues = selectedCapabilityIssues(catalog, plan, sqliteRuntimeVersion())
  if capabilityIssues.len > 0:
    result.executionConfirmed = true
    for issue in capabilityIssues: result.errors.add issue
    db.close()
    emit(result, jsonOutput)
    return 1
  result.planned = plan.steps
  result.skipped = plan.skipped
  result.executionConfirmed = true
  if preview:
    db.close()
    emit(result, jsonOutput)
    return resultExitCode(result)
  db.close()
  # A writable run re-reads, revalidates and replans under the accepted lock.
  try:
    let writable = openDatabase(databasePath)
    defer: writable.close()
    let executed = runMigrations(writable, catalog, request,
      (proc(): bool = cancellationRequested()))
    emit(executed, jsonOutput)
    return resultExitCode(executed)
  except CatchableError as error:
    return failure(name, databasePath, "migration_failed", error.msg, jsonOutput)

const ScaffoldApplicationEntry = staticRead("templates/scaffold/model_application.nim")
const LegacyApplicationEntry = staticRead("templates/scaffold/application.nim")

proc decodeSignedVersion(node: JsonNode, value: var int64): bool =
  ## Bounded decimal (optionally signed) version string; no overflow, no coercion.
  if node.kind != JString: return false
  let raw = node.getStr
  if raw.len == 0: return false
  var index = 0
  var negative = false
  if raw[0] == '-':
    negative = true
    index = 1
    if raw.len == 1: return false
  if negative:
    # Accumulate negatively so low(int64) stays representable.
    var parsed: int64
    while index < raw.len:
      let character = raw[index]
      if character notin {'0'..'9'}: return false
      let digit = int64(ord(character) - ord('0'))
      if parsed < (low(int64) + digit) div 10: return false
      parsed = parsed * 10 - digit
      inc index
    value = parsed
  else:
    var parsed: int64
    while index < raw.len:
      let character = raw[index]
      if character notin {'0'..'9'}: return false
      let digit = int64(ord(character) - ord('0'))
      if parsed > (high(int64) - digit) div 10: return false
      parsed = parsed * 10 + digit
      inc index
    value = parsed
  true

proc decodePositiveVersion(node: JsonNode, value: var int64): bool =
  ## Plans, statuses, skipped and pending are real migration versions (> 0).
  if not decodeSignedVersion(node, value): return false
  value > 0

proc decodeCurrentVersion(node: JsonNode, value: var int64): bool =
  ## A known current version may be 0 (known-empty history).
  if not decodeSignedVersion(node, value): return false
  value >= 0

proc decodeIssueNode(node: JsonNode, issue: var MigrationIssue): bool =
  if node.kind != JObject: return false
  for field in ["code", "message", "file", "version", "direction"]:
    if field notin node: return false
  if node["code"].kind != JString or node["message"].kind != JString or
      node["file"].kind != JString: return false
  issue.code = node["code"].getStr
  issue.message = node["message"].getStr
  issue.file = node["file"].getStr
  case node["version"].kind
  of JNull: issue.version = none(int64)
  of JString:
    var value: int64
    if not decodeSignedVersion(node["version"], value): return false
    issue.version = some(value)
  else: return false
  case node["direction"].kind
  of JNull: issue.direction = none(MigrationDirection)
  of JString:
    case node["direction"].getStr
    of "up": issue.direction = some(mdUp)
    of "down": issue.direction = some(mdDown)
    else: return false
  else: return false
  true

proc decodeStepNode(node: JsonNode, step: var MigrationStep): bool =
  if node.kind != JObject: return false
  for field in ["version", "direction", "name", "file", "statements"]:
    if field notin node: return false
  var version: int64
  if not decodePositiveVersion(node["version"], version): return false
  step.version = version
  if node["direction"].kind != JString: return false
  case node["direction"].getStr
  of "up": step.direction = mdUp
  of "down": step.direction = mdDown
  else: return false
  if node["name"].kind != JString or node["file"].kind != JString: return false
  step.name = node["name"].getStr
  step.sourcePath = node["file"].getStr
  if node["statements"].kind != JArray: return false
  for statement in node["statements"]:
    if statement.kind != JString: return false
    step.statements.add statement.getStr
  true

proc decodeStatusNode(node: JsonNode, status: var MigrationStatus): bool =
  if node.kind != JObject: return false
  for field in ["version", "name", "file", "state", "issues"]:
    if field notin node: return false
  var version: int64
  if not decodePositiveVersion(node["version"], version): return false
  status.version = version
  if node["name"].kind != JString or node["file"].kind != JString or
      node["state"].kind != JString: return false
  status.name = node["name"].getStr
  status.file = node["file"].getStr
  status.state = node["state"].getStr
  if status.state notin ["up", "down", "pending-template", "corrupt",
      "unknown-format", "missing", "legacy-unverified-down", "modified"]:
    return false
  if node["issues"].kind != JArray: return false
  for issue in node["issues"]:
    var decoded: MigrationIssue
    if not decodeIssueNode(issue, decoded): return false
    status.issues.add decoded
  true

proc decodeReport*(text, command: string, dryRun: bool,
    output: var MigrationResult): bool =
  ## Total typed decoder from the authoritative resultJson document. Every field
  ## is kind-checked before any access or iteration, so no Assertion/Field/
  ## Overflow defect can escape and no partial document is ever trusted.
  try:
    let node = parseJson(text)
    if node.kind != JObject: return false
    for field in ["command", "database", "dry_run", "execution_confirmed", "planned",
        "executed", "skipped", "current_version", "pending_versions", "statuses",
        "errors"]:
      if field notin node: return false
    if node["command"].kind != JString or node["command"].getStr != command: return false
    if node["database"].kind != JString: return false
    if node["dry_run"].kind != JBool or node["dry_run"].getBool != dryRun: return false
    if node["execution_confirmed"].kind != JBool: return false
    let confirmed = node["execution_confirmed"].getBool
    if confirmed:
      if node["executed"].kind != JArray: return false
    elif node["executed"].kind != JNull: return false
    if node["planned"].kind != JArray or node["skipped"].kind != JArray or
        node["statuses"].kind != JArray or node["errors"].kind != JArray: return false
    if node["current_version"].kind notin {JString, JNull}: return false
    if node["pending_versions"].kind notin {JArray, JNull}: return false
    # The producer's nullable contract: pending is an array iff the execution is
    # confirmed AND the current version is known; an unconfirmed result carries
    # null executed/current/pending. Inconsistent combinations are rejected.
    if confirmed:
      if node["current_version"].kind == JString:
        if node["pending_versions"].kind != JArray: return false
      else:
        if node["pending_versions"].kind != JNull: return false
    else:
      if node["current_version"].kind != JNull or
          node["pending_versions"].kind != JNull: return false
    output = MigrationResult(command: node["command"].getStr,
      database: node["database"].getStr, dryRun: node["dry_run"].getBool,
      executionConfirmed: confirmed)
    for step in node["planned"]:
      var decoded: MigrationStep
      if not decodeStepNode(step, decoded): return false
      output.planned.add decoded
    if confirmed:
      for step in node["executed"]:
        var decoded: MigrationStep
        if not decodeStepNode(step, decoded): return false
        output.executed.add decoded
    for version in node["skipped"]:
      var value: int64
      if not decodePositiveVersion(version, value): return false
      output.skipped.add value
    if node["current_version"].kind == JString:
      var value: int64
      if not decodeCurrentVersion(node["current_version"], value): return false
      output.currentVersion = some(value)
    else:
      output.currentVersion = none(int64)
    if node["pending_versions"].kind == JArray:
      for version in node["pending_versions"]:
        var value: int64
        if not decodePositiveVersion(version, value): return false
        output.pendingVersions.add value
    for status in node["statuses"]:
      var decoded: MigrationStatus
      if not decodeStatusNode(status, decoded): return false
      output.statuses.add decoded
    for issue in node["errors"]:
      var decoded: MigrationIssue
      if not decodeIssueNode(issue, decoded): return false
      output.errors.add decoded
    true
  except CatchableError:
    false

proc executeDatabaseInit*(project: Project, dryRun: bool): int =
  ## Install configuration and catalog; never open storage or edit the entry.
  for action in initializeDatabaseProject(project, dryRun):
    stdout.writeLine(action)
  if dryRun: return 0
  # Only a byte-identical generated entry proves automatic startup ownership; an
  # unrelated custom file must never be described as already wired.
  let entry = project.root / "app" / "application.nim"
  let generated = fileExists(entry) and
    readFile(entry) in [ScaffoldApplicationEntry, LegacyApplicationEntry]
  if generated:
    stdout.writeLine("configuration ready; the generated application entry already opens storage")
  else:
    stdout.writeLine("configuration ready; if your entry point does not already open storage, add:")
    stdout.writeLine("  import ./config/database")
    stdout.writeLine("  let db = openApplicationDatabase()")
    stdout.writeLine("see db/migrations/README.md for the startup example")
  0

proc interruptedReport(command: string, message: string,
    dryRun = false): MigrationResult =
  ## A forced stop never claims which steps committed, but keeps the request flags.
  result.command = command
  result.dryRun = dryRun
  result.executionConfirmed = false
  result.errors.add MigrationIssue(code: "interrupted_unconfirmed", message: message)

proc executeDatabaseCommand*(project: Project, request: MigrationRequest,
    dryRun, jsonOutput: bool): int =
  ## Compile and supervise the maintenance program for one database command.
  let name = commandName(request.kind)
  if not fileExists(project.root / "config" / "database.nim") or
      not fileExists(project.root / "db" / "catalog.nim"):
    return failure(name, "", "configuration_missing",
      "run leaf db init first: config/database.nim and db/catalog.nim are required", jsonOutput,
      dryRun)
  let directory = project.root / MaintenanceRelative
  createDir(directory)
  let entry = project.root / MaintenanceEntry
  let source = maintenanceSource()
  if not fileExists(entry) or readFile(entry) != source: writeFile(entry, source)
  let binary = project.root / MaintenanceBinary
  # Interrupt handling covers the compile phase too, so a signal is reported
  # instead of killing the CLI before it can print a stable report.
  beginInterruptHandling()
  defer: endInterruptHandling()
  var job: BuildJob
  try:
    job = startHeadlessBuild(project, entry, binary, directory)
  except CatchableError as error:
    return failure(name, "", "compile_failed",
      "cannot start the maintenance build: " & error.msg, jsonOutput, dryRun)
  var compileInterrupted = false
  var compileFailed = false
  try:
    while not job.pollBuild():
      if wasInterrupted(): break
      sleep(10)
    compileInterrupted = wasInterrupted() and job.code == -1
    compileFailed = job.code != 0 and not compileInterrupted
    if compileInterrupted:
      stderr.writeLine(job.output)
      emit(interruptedReport(name, "interrupted while compiling the maintenance program",
        dryRun), jsonOutput)
      return 130
    if compileFailed: stderr.writeLine(job.output)
  finally:
    job.close()
  if compileFailed:
    return failure(name, "", "compile_failed",
      "maintenance program failed to compile", jsonOutput, dryRun)
  # Unique per-run token and report paths under target: the token stays absent
  # until cancellation and every temporary is removed only after the child is
  # reaped, in a true finally.
  let unique = $getCurrentProcessId() & "-" & $getMonoTime().ticks
  let token = directory / ("cancel-" & unique & ".token")
  let report = directory / ("report-" & unique & ".json")
  for path in [token, report, report & ".tmp"]:
    if fileExists(path): removeFile(path)
  var env = newStringTable(modeCaseSensitive)
  for key, value in envPairs(): env[key] = value
  env[CancelTokenEnv] = token
  env[ReportEnv] = report
  var process: SplitProcess
  try:
    process = startSplitManaged(binary, childArgs(request, dryRun, jsonOutput),
      project.root, env)
  except CatchableError as error:
    return failure(name, "", "protocol_error",
      "cannot start the maintenance program: " & error.msg, jsonOutput, dryRun)
  var requested = false
  var forced = false
  var deadline = getMonoTime()
  var reportText = ""
  var cleanupUnconfirmed = false
  try:
    while not process.pollSplit():
      if wasInterrupted() and not requested:
        requested = true
        deadline = getMonoTime() + initDuration(seconds = GracefulCancelSeconds)
        writeFile(token, "cancel")
      if requested and getMonoTime() > deadline:
        forced = true
        break
      sleep(10)
  finally:
    # Owned reap first; diagnostics and the report handoff are fallible and must
    # never skip cleanup.
    process.closeSplit()
    cleanupUnconfirmed = process.cleanupUnconfirmed or process.protocolError
    try:
      # The child's own channels are diagnostics only: stdout carries exactly
      # one official report object.
      if process.stdoutText.len > 0: stderr.write(process.stdoutText)
      if process.stderrText.len > 0: stderr.write(process.stderrText)
    except CatchableError:
      discard
    try:
      if fileExists(report): reportText = readFile(report)
    except CatchableError:
      discard
    for path in [token, report, report & ".tmp"]:
      if fileExists(path):
        try:
          removeFile(path)
        except CatchableError as cleanupError:
          # A failed removal is disclosed but must never skip the later ones.
          try: stderr.writeLine("leaf: could not remove " & path & ": " & cleanupError.msg)
          except CatchableError: discard
  if forced:
    emit(interruptedReport(name,
      "the maintenance program did not stop within " & $GracefulCancelSeconds &
      "s; run status to verify the committed state", dryRun), jsonOutput)
    return 130
  var decoded: MigrationResult
  if reportText.len > 0:
    if not decodeReport(reportText, name, dryRun, decoded):
      # Malformed transport: one stable controlled failure with the caller flags.
      var result = MigrationResult(command: name, executionConfirmed: false)
      result.dryRun = dryRun
      result.errors.add MigrationIssue(code: "malformed_report",
        message: "the maintenance program produced an invalid report")
      emit(result, jsonOutput)
      return 1
    if cleanupUnconfirmed:
      decoded.errors.add MigrationIssue(code: "cleanup_unconfirmed",
        message: "the maintenance process tree could not be confirmed cleaned")
      stderr.writeLine("leaf: owned process cleanup could not be confirmed")
    # JSON and text are both rendered from the same validated document.
    if jsonOutput: stdout.writeLine(resultJson(decoded).pretty())
    else: stdout.writeLine(resultText(decoded))
    return (if cleanupUnconfirmed: 1 else: process.code)
  if cleanupUnconfirmed:
    # No report and no confirmable cleanup: truthful unknown state.
    var result = MigrationResult(command: name, executionConfirmed: false)
    result.dryRun = dryRun
    result.errors.add MigrationIssue(code: "cleanup_unconfirmed",
      message: "the maintenance process tree could not be confirmed cleaned")
    emit(result, jsonOutput)
    return 1
  # An exit without a report is a failure, not an interruption, unless the run
  # was actually cancelled or the child returned the interrupt status.
  var result = MigrationResult(command: name, executionConfirmed: false)
  result.dryRun = dryRun
  if requested or process.code == 130:
    result.errors.add MigrationIssue(code: "interrupted_unconfirmed",
      message: "the maintenance program stopped without a report; run status to verify")
    emit(result, jsonOutput)
    return 130
  result.errors.add MigrationIssue(code: "maintenance_failed",
    message: "the maintenance program exited without a report (status " &
      $process.code & ")")
  emit(result, jsonOutput)
  return 1
